#!/usr/bin/env bash
# Build the local media + fixture pack for the editor prototype (phase 03).
# Idempotent: every run wipes and regenerates public/media and public/fonts/captions.
#
#   scripts/build-media.sh                 # uses the defaults below
#   DEMO_SRC=/path/clip.mp4 MEDIA_CACHE=/tmp/x scripts/build-media.sh
#
# Inputs (never copied into the repo as-is):
#   DEMO_SRC     demo gameplay clip (third-party footage, internal only)
#   MEDIA_CACHE  download cache filled by scripts/fetch-assets.sh (run automatically if empty)
# Outputs: public/media/** (+ manifest.json) and public/fonts/captions/*.woff2
# Needs: ffmpeg-full (libx264, libvpx, libwebp, libmp3lame), ImageMagick 7, macOS `say`, python3.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEMO_SRC="${DEMO_SRC:-$ROOT/../../.onboarding/live-src/valorant-60s.mp4}"
MEDIA_CACHE="${MEDIA_CACHE:-${TMPDIR:-/tmp}/sl-media-cache}"
FF_BIN="${FF_BIN:-/opt/homebrew/opt/ffmpeg-full/bin}"
FF="$FF_BIN/ffmpeg -nostdin -y -hide_banner -loglevel error"
OUT="$ROOT/public/media"
FONT_OUT="$ROOT/public/fonts/captions"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/sl-media-build.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
ENTRIES="$WORK/entries.tsv"
GEN="Generated by scripts/build-media.sh"
GEN_LIC="Own work, no third-party rights (CC0-equivalent)"
EK_LIC="Eklipse in-app catalogue asset; rights as held by Eklipse; internal prototype use only"

[ -f "$DEMO_SRC" ] || { echo "DEMO_SRC not found: $DEMO_SRC" >&2; exit 1; }
[ -s "$MEDIA_CACHE/memes.json" ] || "$ROOT/scripts/fetch-assets.sh" "$MEDIA_CACHE"
TEXT_FONT="$MEDIA_CACHE/fonts/bangers/package/files/bangers-latin-400-normal.woff"

rm -rf "$OUT" "$FONT_OUT"
mkdir -p "$OUT"/{memes,sfx,music,tts,stickers,gifs,emotes} "$FONT_OUT"
add() { printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$@" >> "$ENTRIES"; } # path kind category title source licence note

# ---------- 1. demo clip, poster, filmstrip, waveform ----------
DEMO_NOTE="Third-party Valorant stream recording; internal only (Hub login), never on public pages"
$FF -i "$DEMO_SRC" -vf "fps=30,scale=1280:720" -c:v libx264 -preset slow -crf 28 -maxrate 800k -bufsize 1600k -profile:v high \
  -pix_fmt yuv420p -g 30 -keyint_min 30 -sc_threshold 0 -c:a aac -b:a 128k -ac 2 \
  -movflags +faststart "$OUT/demo.mp4"
$FF -ss 22 -i "$OUT/demo.mp4" -frames:v 1 -q:v 4 "$OUT/demo-poster.jpg"
$FF -i "$OUT/demo.mp4" -vf "fps=1,scale=160:90,tile=10x6" -frames:v 1 -q:v 5 "$OUT/filmstrip.jpg"
$FF -i "$OUT/demo.mp4" -vn -ac 1 -ar 8000 -f s16le "$WORK/demo.pcm"
add media/demo.mp4 video demo "Demo clip (Valorant, 60 s)" "Internal Valorant test recording (60 s), re-encoded" internal-only "$DEMO_NOTE; 720p30 H.264 CRF28 capped 800k, keyframe every 1 s"
add media/demo-poster.jpg image demo "Demo poster (t=22 s)" "$GEN from demo.mp4" internal-only "$DEMO_NOTE"
add media/filmstrip.jpg image demo "Timeline filmstrip" "$GEN from demo.mp4" internal-only "Sprite 1600x540: 10 cols x 6 rows of 160x90 tiles, tile n = second n (row-major)"
add media/waveform.json data demo "Audio peaks" "$GEN from demo.mp4" internal-only "100 peaks per second, normalised 0-1"

# ---------- 2. Eklipse memes (VP9-alpha WebM preview + green-screen MP4) ----------
python3 -I - "$MEDIA_CACHE/memes.json" > "$WORK/memes.tsv" <<'PY'
import json, re, sys
for m in json.load(open(sys.argv[1]))["data"][:12]:
    title = re.sub(r"\s+", " ", m["title"].replace("_ ", ", ").replace("_", "'")).strip()
    title = re.sub(r"(?i)\s*(meme)?\s*green screen\s*\d*$", "", title).strip() or title
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    if len(slug) > 40: slug = slug[:41].rsplit("-", 1)[0]
    print(m["id"], f"{slug}-{m['id']}", title, m.get("type") or "", sep="\t")
PY
while IFS=$'\t' read -r id slug title type; do
  $FF -c:v libvpx -i "$MEDIA_CACHE/memes/$id.webm" -an -vf "scale=240:-2,fps=20" -c:v libvpx-vp9 \
    -pix_fmt yuva420p -b:v 0 -crf 42 -deadline good -cpu-used 4 -row-mt 1 "$OUT/memes/$slug.webm"
  $FF -i "$MEDIA_CACHE/memes/$id.mp4" -vf "scale=320:-2,fps=20" -c:v libx264 -preset slow -crf 30 \
    -c:a aac -b:a 64k -ac 1 -movflags +faststart "$OUT/memes/$slug.mp4"
  add "media/memes/$slug.webm" meme overlay "$title" "eklipse-assets.eklipse.gg/previews/$id.webm (QC /v1/public/memes)" "$EK_LIC" "Transparent VP9-alpha preview, silent"
  add "media/memes/$slug.mp4" meme "${type:-green}" "$title" "eklipse-assets.eklipse.gg/memes/$id.mp4 (QC /v1/public/memes)" "$EK_LIC" "Green-screen clip with sound"
done < "$WORK/memes.tsv"
# 4 alpha-WebM stickers reuse meme previews (catalogue has no separate sticker set)
head -4 "$WORK/memes.tsv" | while IFS=$'\t' read -r id slug title type; do
  cp "$OUT/memes/$slug.webm" "$OUT/stickers/meme-$slug.webm"
  add "media/stickers/meme-$slug.webm" sticker-webm "Animated" "$title" "Copy of media/memes/$slug.webm" "$EK_LIC" "Alpha WebM sticker"
done

# ---------- 3. sound effects: Eklipse sounds + generated fills ----------
# id|category|slug|title  (catalogue titles are truncated, e.g. "erd emoji" = nerd emoji)
cat > "$WORK/sfx-map.txt" <<'MAP'
1622|Alerts & Notifications|talent-show-buzzer|Talent show buzzer
1616|Alerts & Notifications|denied|Denied
1617|Alerts & Notifications|ok-ramm|OK (Ramm)
1618|Alerts & Notifications|short-pop|Short pop
1628|Gaming|headshot|Headshot
1625|Gaming|blaster-shot|Blaster shot
1615|Gaming|laser-sight|Laser sight
1624|Gaming|duar-boom|Duar boom
1627|Reaction Sounds|best-cry-ever|Best cry ever
1620|Reaction Sounds|cat-scream|Cat scream
1623|Reaction Sounds|lets-go-shout|Let's go shout
1619|Reaction Sounds|nerd-emoji|Nerd emoji
MAP
cat_slug() { echo "$1" | tr 'A-Z' 'a-z' | sed -e 's/&//g' -e 's/[^a-z0-9]\{1,\}/-/g' -e 's/-$//'; }
while IFS='|' read -r id cat slug title; do
  f="sfx/$(cat_slug "$cat")-$slug.mp3"
  $FF -i "$MEDIA_CACHE/sounds/$id.mp3" -t 20 -c:a libmp3lame -b:a 128k "$OUT/$f"
  add "media/$f" sfx "$cat" "$title" "eklipse-assets.eklipse.gg/sounds/$id.mp3 (QC /v1/public/sounds)" "$EK_LIC" "Trimmed to <= 20 s"
done < "$WORK/sfx-map.txt"
gen_sfx() { # category slug title note filter-input-args...
  local cat=$1 slug=$2 title=$3 note=$4; shift 4
  local f="sfx/$(cat_slug "$cat")-$slug.mp3"
  $FF "$@" -c:a libmp3lame -b:a 128k "$OUT/$f"
  add "media/$f" sfx "$cat" "$title" "$GEN (ffmpeg synthesis)" "$GEN_LIC" "$note"
}
gen_sfx "Alerts & Notifications" notification-ding "Notification ding" "Two-tone sine chime" \
  -f lavfi -i "aevalsrc='0.5*sin(2*PI*1320*t)*exp(-6*t)+0.4*sin(2*PI*1760*t)*exp(-6*(t-0.12))*gt(t,0.12)':d=1.2:s=44100"
gen_sfx "Ambient Sounds" rain "Rain" "Pink noise, low-passed" \
  -f lavfi -i "anoisesrc=c=pink:a=0.35:d=12:r=44100" -af "lowpass=f=3500,afade=t=in:d=1,afade=t=out:st=11:d=1"
gen_sfx "Ambient Sounds" wind "Wind" "Brown noise with slow tremolo" \
  -f lavfi -i "anoisesrc=c=brown:a=0.6:d=12:r=44100" -af "tremolo=f=0.3:d=0.6,lowpass=f=900,afade=t=in:d=1,afade=t=out:st=11:d=1"
gen_sfx "Ambient Sounds" crowd-murmur "Crowd murmur" "Band-passed noise" \
  -f lavfi -i "anoisesrc=c=white:a=0.3:d=12:r=44100" -af "bandpass=f=500:w=400,tremolo=f=3:d=0.3,afade=t=in:d=1,afade=t=out:st=11:d=1"
gen_sfx "Time & Speed" clock-tick "Clock tick" "1 Hz tick-tock" \
  -f lavfi -i "aevalsrc='0.7*sin(2*PI*(2000-600*mod(floor(t),2))*t)*exp(-120*mod(t,1))':d=6:s=44100"
gen_sfx "Time & Speed" whoosh "Whoosh" "Noise swell" \
  -f lavfi -i "anoisesrc=c=pink:a=0.8:d=1.2:r=44100" -af "bandpass=f=1200:w=1500,afade=t=in:d=0.6:curve=exp,afade=t=out:st=0.6:d=0.6"
gen_sfx "Time & Speed" rewind "Rewind" "Falling pitch sweep" \
  -f lavfi -i "aevalsrc='0.4*sin(2*PI*(1800*t-700*t*t))':d=1.2:s=44100" -af "afade=t=out:st=0.9:d=0.3"

# ---------- 4. music loops (30 s, generated) ----------
# name|title|bpm|root Hz|third (3 minor, 4 major)|wave (sin|sq)
cat > "$WORK/music.txt" <<'MAP'
chill-lofi|Chill Lo-fi|80|220|3|sin
hype-arena|Hype Arena|128|110|3|sq
retro-arcade|Retro Arcade|140|262|4|sq
dark-tension|Dark Tension|90|98|3|sin
upbeat-pop|Upbeat Pop|116|196|4|sin
ambient-pad|Ambient Pad|60|147|4|sin
MAP
while IFS='|' read -r slug title bpm f third wave; do
  w() { [ "$wave" = sq ] && echo "0.6*sgn(sin($1))" || echo "sin($1)"; }
  semi="(eq(mod(floor(t*$bpm/240),4),1)*5+eq(mod(floor(t*$bpm/240),4),2)*7+eq(mod(floor(t*$bpm/240),4),3)*(-2))"
  r="$f*pow(2,$semi/12)"
  pad="0.12*($(w "2*PI*$r*t")+$(w "2*PI*$r*pow(2,$third/12)*t")+$(w "2*PI*$r*1.5*t"))"
  kick="0.5*sin(2*PI*55*t)*exp(-12*mod(t*$bpm/60,1))"
  hat="0.06*(2*random(0)-1)*exp(-40*mod(t*$bpm/30,1))"
  $FF -f lavfi -i "aevalsrc='$pad+$kick+$hat':d=30:s=44100" -af "lowpass=f=6000,afade=t=in:d=0.5,afade=t=out:st=28.5:d=1.5,volume=0.8" \
    -ac 2 -c:a aac -b:a 96k "$OUT/music/$slug.m4a"
  add "media/music/$slug.m4a" music "Music" "$title" "$GEN (ffmpeg synthesis, $bpm BPM)" "$GEN_LIC" "Simple chord loop, placeholder for a licensed library"
done < "$WORK/music.txt"

# ---------- 5. TTS mock voices (macOS say) ----------
LINE="Wait for it... that was the cleanest clutch of the night!"
for v in Samantha Daniel Karen; do
  slug=$(echo "$v" | tr 'A-Z' 'a-z')
  say -v "$v" -o "$WORK/$slug.aiff" "$LINE"
  $FF -i "$WORK/$slug.aiff" -c:a aac -b:a 96k "$OUT/tts/$slug.m4a"
  add "media/tts/$slug.m4a" tts "Mock" "$v" "macOS say -v $v" "Apple system voice output; mock, internal only" "Line: $LINE"
done

source "$ROOT/scripts/build-media-graphics.sh"

# ---------- 9. caption fonts ----------
while IFS='|' read -r pkg file family weight lic; do
  cp "$MEDIA_CACHE/fonts/$pkg/package/files/$file" "$FONT_OUT/$pkg-$weight.woff2"
  add "fonts/captions/$pkg-$weight.woff2" font "Caption" "$family $weight" "npm @fontsource/$pkg" "$lic" "Latin subset"
done <<'MAP'
montserrat|montserrat-latin-800-normal.woff2|Montserrat|800|OFL-1.1
bangers|bangers-latin-400-normal.woff2|Bangers|400|OFL-1.1
anton|anton-latin-400-normal.woff2|Anton|400|OFL-1.1
poppins|poppins-latin-800-normal.woff2|Poppins|800|OFL-1.1
luckiest-guy|luckiest-guy-latin-400-normal.woff2|Luckiest Guy|400|Apache-2.0
bebas-neue|bebas-neue-latin-400-normal.woff2|Bebas Neue|400|OFL-1.1
MAP

# ---------- 10. waveform.json + manifest.json ----------
python3 -I - "$ROOT/public" "$ENTRIES" "$WORK/demo.pcm" "$FF_BIN/ffprobe" <<'PY'
import array, json, os, subprocess, sys
pub, entries, pcm, ffprobe = sys.argv[1:5]
a = array.array("h"); a.frombytes(open(pcm, "rb").read())
step = 80  # 8000 Hz / 100 peaks per second
peaks = [max((abs(x) for x in a[i:i + step]), default=0) for i in range(0, len(a), step)]
top = max(peaks) or 1
json.dump({"peaksPerSecond": 100, "sampleRate": 8000, "durationMs": round(len(a) / 8),
           "peaks": [round(p / top, 3) for p in peaks]},
          open(os.path.join(pub, "media/waveform.json"), "w"), separators=(",", ":"))
items = []
for line in open(entries):
    path, kind, cat, title, src, lic, note = line.rstrip("\n").split("\t")
    it = {"path": path, "kind": kind, "category": cat, "title": title, "source": src, "licence": lic, "note": note}
    if path.endswith((".mp4", ".webm", ".mp3", ".m4a", ".webp")):
        d = subprocess.run([ffprobe, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                            os.path.join(pub, path)], capture_output=True, text=True).stdout.strip()
        if d and d != "N/A": it["durationMs"] = round(float(d) * 1000)
    it["bytes"] = os.path.getsize(os.path.join(pub, path))
    items.append(it)
json.dump({"generatedBy": "scripts/build-media.sh", "pathBase": "public root (prototype base URL)",
           "count": len(items), "items": items}, open(os.path.join(pub, "media/manifest.json"), "w"), indent=1)
print(f"manifest: {len(items)} items")
PY
du -sh "$OUT" "$FONT_OUT"
